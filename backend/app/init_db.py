import asyncio
from sqlalchemy import text

from .db import Base, engine
from .runtime import loop_factory
from .admin_auth import ensure_admin_account
from .pass_keys import new_pass_key


async def main():
    async with engine.begin() as connection:
        await connection.run_sync(Base.metadata.create_all)
        # Additive, repeatable upgrade for local databases created before grade selection.
        await connection.execute(text(
            "ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS grade INTEGER "
            "CONSTRAINT ck_enquiries_grade CHECK (grade BETWEEN 1 AND 11)"
        ))
        await connection.execute(text("ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS reference_number BIGINT GENERATED BY DEFAULT AS IDENTITY"))
        await connection.execute(text("CREATE UNIQUE INDEX IF NOT EXISTS uq_enquiries_reference_number ON enquiries (reference_number)"))
        await connection.execute(text("ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS staff_received_at TIMESTAMPTZ"))
        await connection.execute(text("ALTER TABLE enquiries ADD COLUMN IF NOT EXISTS phone VARCHAR(20)"))
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS pinned BOOLEAN NOT NULL DEFAULT FALSE"))
        # Categories became admin-defined labels; convert the two original fixed codes once.
        await connection.execute(text("ALTER TABLE notices DROP CONSTRAINT IF EXISTS ck_notices_category"))
        await connection.execute(text("ALTER TABLE notices ALTER COLUMN category TYPE VARCHAR(40)"))
        await connection.execute(text("CREATE INDEX IF NOT EXISTS ix_notices_category ON notices (category)"))
        await connection.execute(text("UPDATE notices SET category = 'News' WHERE category = 'news'"))
        await connection.execute(text("UPDATE notices SET category = 'Admission guide' WHERE category = 'admission_guide'"))
        # Notices became multilingual; existing ones were written in English.
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS title_uz VARCHAR(160)"))
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS body_uz TEXT"))
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS title_en VARCHAR(160)"))
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS body_en TEXT"))
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS title_ru VARCHAR(160)"))
        await connection.execute(text("ALTER TABLE notices ADD COLUMN IF NOT EXISTS body_ru TEXT"))
        await connection.execute(text("UPDATE notices SET title_en = title, body_en = body WHERE title_uz IS NULL AND title_en IS NULL AND title_ru IS NULL"))
        # Every student has a readable pass key. Students without one (added before pass keys, or while keys
        # were kept only as digests, which cannot be turned back into keys) are given a new key once.
        await connection.execute(text("ALTER TABLE students ADD COLUMN IF NOT EXISTS pass_key VARCHAR(14)"))
        for student_id in (await connection.execute(text("SELECT id FROM students WHERE pass_key IS NULL"))).scalars().all():
            await connection.execute(text("UPDATE students SET pass_key = :key WHERE id = :id"), {"key": new_pass_key(), "id": student_id})
        await connection.execute(text("ALTER TABLE students ALTER COLUMN pass_key SET NOT NULL"))
        await connection.execute(text("CREATE UNIQUE INDEX IF NOT EXISTS uq_students_pass_key ON students (pass_key)"))
        await connection.execute(text("ALTER TABLE students DROP COLUMN IF EXISTS pass_key_hash"))
    await engine.dispose()
    ensure_admin_account()
    print("Local admissions database initialized.")


if __name__ == "__main__":
    asyncio.run(main(), loop_factory=loop_factory)
